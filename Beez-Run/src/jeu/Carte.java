    public boolean isSolidPixel(double px, double py) {
    int tx = (int)(px / FRAME_SIZE);
    int ty = (int)(py / FRAME_SIZE);
    return isSolidTile(tx, ty);
    }

    public boolean isSolidTile(int tx, int ty) {
    if (tx < 0 || tx >= COLS || ty < 0 || ty >= ROWS) {
        return true; // fora do mapa = parede (padrão)
    }

    int c1 = colision[ty][tx];
    int c2 = colision2[ty][tx];

    // IGNORA 38 (transparente): só colide se for diferente de 38
    return (c1 != TILE_EMPTY) || (c2 != TILE_EMPTY);
    }

    
    private void drawLayer(Graphics2D g, int[][] layer, int[][] layerRot) {
        for (int y = 0; y < ROWS; y++) {
            for (int x = 0; x < COLS; x++) {
                BufferedImage sprite = SpriteSheet.getFrame(layer[y][x]);
                
                switch(layerRot[y][x]){
                    case 0:
                        g.drawImage(sprite, (int) x * FRAME_SIZE, (int) y * FRAME_SIZE, FRAME_SIZE, FRAME_SIZE, null);
                        break;
                    case 1:
                        g.drawImage(sprite, (int) (x * FRAME_SIZE) + FRAME_SIZE, (int) y * FRAME_SIZE, -FRAME_SIZE, FRAME_SIZE, null);
                        break;
                    case 2:
                        g.drawImage(sprite, (int) (x * FRAME_SIZE), (int) (y * FRAME_SIZE) + FRAME_SIZE, FRAME_SIZE, -FRAME_SIZE, null);
                        break;
                    case 3:
                        drawSprite90(g, sprite, x * 64, y * 64);
                        break;
                }
                
            }
        }
    }
    
    public void drawSprite90(Graphics2D g, BufferedImage sprite, int x, int y) {

    AffineTransform old = g.getTransform();

        g.translate(x + sprite.getWidth() / 2, y + sprite.getHeight() / 2);
        g.rotate(Math.toRadians(90));
        g.drawImage(sprite, -sprite.getWidth() / 2, -sprite.getHeight() / 2, null);

        g.setTransform(old);
    }
